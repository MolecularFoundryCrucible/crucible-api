"""Turn a schema-only dump of a reference database into migrations/schema/baseline_<revision>.sql.

Usage:
    python scripts/make_schema_baseline.py DUMP.sql REVISION

DUMP.sql is `pg_dump --schema-only --no-owner --no-privileges` of a database at REVISION, made with
a PostgreSQL 17 client. See migrations/README.md.
"""
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

# Comments on the public schema and on extensions need ownership of them, which the application's
# database user may not have; CREATE EXTENSION sets the extensions' own comments anyway.
DROPPED_OBJECTS = (
    "-- Name: SCHEMA public; Type: COMMENT;",
    "-- Name: EXTENSION pg_trgm; Type: COMMENT;",
    "-- Name: EXTENSION vector; Type: COMMENT;",
    "-- Name: source; Type: SCHEMA;",
    "-- Name: alembic_version; Type: TABLE;",
    "-- Name: alembic_version alembic_version_pkc; Type: CONSTRAINT;",
)

# PostgreSQL prints `column IN ('a', 'b')` on a varchar column as an ANY(ARRAY[...]::text[])
# expression, and reads that text back as a different but equivalent expression, so a database
# built from the dump would not compare equal to the reference. Write these back as IN lists.
ELEMENT = r"'((?:[^']|'')*)'::character varying"
IN_LIST = re.compile(r"\(\((\w+)\)::text (= ANY|<> ALL) \(\(ARRAY\[(" + ELEMENT + r"(?:, " + ELEMENT + r")*)\]\)::text\[\]\)\)")

SEED = """
--
-- Rows the application looks up by fixed name.
--

INSERT INTO public.accessgroup (group_name, group_type) VALUES ('public', 'system') ON CONFLICT DO NOTHING;
"""


def _as_in_list(match: re.Match) -> str:
    values = ", ".join(f"'{value}'" for value in re.findall(ELEMENT, match.group(3)))
    operator = "IN" if match.group(2) == "= ANY" else "NOT IN"
    return f"({match.group(1)} {operator} ({values}))"


def make_baseline(dump: str, revision: str) -> str:
    lines = [line for line in dump.split("\n") if not line.startswith(("\\restrict", "\\unrestrict"))]
    blocks = re.split(r"(?=^--\n-- (?:Name|Data for Name): )", "\n".join(lines), flags=re.M)
    kept = [block for block in blocks if not any(block.startswith("--\n" + name) for name in DROPPED_OBJECTS)]
    if len(blocks) - len(kept) != len(DROPPED_OBJECTS):
        raise SystemExit("The dump does not contain exactly the expected objects to drop; review DROPPED_OBJECTS")
    body = IN_LIST.sub(_as_in_list, "".join(kept))
    header = f"""-- Crucible database schema at Alembic revision {revision}, for new installations.
-- Generated by scripts/make_schema_baseline.py from a schema-only dump of staging; see
-- migrations/README.md. `python -m app.cli.db upgrade` applies it to an empty database, records
-- the revision, then runs the Alembic migrations after it. Do not edit by hand.

"""
    return header + body.rstrip("\n") + "\n" + SEED


if __name__ == "__main__":
    dump_path, revision = sys.argv[1], sys.argv[2]
    target = REPO_ROOT / "migrations" / "schema" / f"baseline_{revision}.sql"
    target.write_text(make_baseline(Path(dump_path).read_text(), revision))
    print(target)
